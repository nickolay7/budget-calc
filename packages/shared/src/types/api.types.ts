/**
 * Общие типы для ответов API.
 * Содержит обёртки для единичного ответа, пагинированного ответа
 * и параметров пагинации.
 */

/** Стандартный ответ API с данными и временной меткой */
export interface ApiResponse<T> {
  /** Полезная нагрузка ответа */
  data: T;
  /** Временная метка формирования ответа */
  timestamp: string;
}

/** Ответ API со списком данных и мета-информацией пагинации */
export interface PaginatedResponse<T> {
  /** Массив элементов на текущей странице */
  data: T[];
  /** Мета-информация о пагинации */
  meta: {
    /** Общее количество элементов */
    total: number;
    /** Номер текущей страницы */
    page: number;
    /** Количество элементов на странице */
    limit: number;
    /** Общее количество страниц */
    totalPages: number;
  };
}

/** Параметры запроса для пагинации */
export interface PaginationParams {
  /** Номер страницы (опционально, по умолчанию 1) */
  page?: number;
  /** Количество записей на странице (опционально, по умолчанию 20) */
  limit?: number;
}
