/**
 * Типы данных, связанные с категориями транзакций.
 * Содержит интерфейс категории, DTO для создания и обновления.
 */

/** Категория транзакции — группировка доходов/расходов */
export interface Category {
  /** Уникальный идентификатор категории */
  id: string;
  /** Название категории */
  name: string;
  /** Иконка категории (может быть null) */
  icon: string | null;
  /** Цвет категории в HEX (может быть null) */
  color: string | null;
  /** Идентификатор пользователя-владельца */
  userId: string;
  /** Дата создания */
  createdAt: string;
}

/** DTO для создания новой категории */
export interface CreateCategoryDto {
  /** Название категории */
  name: string;
  /** Иконка категории (опционально) */
  icon?: string;
  /** Цвет категории в HEX, например #FF5733 (опционально) */
  color?: string;
}

/** DTO для обновления существующей категории */
export interface UpdateCategoryDto {
  /** Новое название (опционально) */
  name?: string;
  /** Новая иконка (опционально) */
  icon?: string;
  /** Новый цвет в HEX (опционально) */
  color?: string;
}
